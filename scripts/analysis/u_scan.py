"""
u_scan.py: sensitivity of the (+1/0) transition level to the Hubbard U.

Reads the static calculations generated by build_u_scan.py (U = 5, 6 and 8 eV,
each charge state at its U = 7.21 eV relaxed geometry) and the U = 7.21 eV
relaxations, and reports eps(+1/0), the cell magnetic moment and the total
energies for each U. A moment outside 2.5-3.6 muB indicates a different 4f
occupation solution, whose energy is not comparable with the others.

Inputs:  abinit/production/<config>_u<U>_<q>_spin.abo and the relaxations,
         results/transition_levels/<config>_kumagai.json
Output:  results/transition_levels/<config>_u_scan.json

Usage:   python scripts/analysis/u_scan.py --config er_ko
"""

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import formation_energy as fe

HA_EV = 27.211386245988

PRODUCTION_U = 7.21
PRODUCTION_RUNS = {
    0: "{c}_relax_spin",
    1: "{c}_relax_qp1_spin",
    -1: "{c}_relax_qm1_spin",
}

SCAN_U = [5.0, 6.0, 8.0]
TAGS = {0: "q0", 1: "qp1", -1: "qm1"}

CORR_JSON = "results/transition_levels/{c}_kumagai.json"
E_VBM = 7.6953


def u_tag(u_ev):
    """File tag of a U value: 5.0 -> 'u5'.
    Used by: main.
    Input: U (eV); returns: str.
    """
    return "u" + f"{u_ev:g}".replace(".", "p")


def moment_of(abo):
    """Final cell magnetization of a run.
    Used by: main.
    Input: .abo path; returns: moment (muB) or None.
    """
    val = None
    for ln in Path(abo).read_text(encoding="utf-8", errors="replace").splitlines():
        if "Magnetization (Bohr magneton)" in ln:
            m = re.search(r"=\s*(-?[\d.]+E?[+-]?\d*)", ln)
            if m:
                val = float(m.group(1))
    return val


def completed(abo):
    """Whether an ABINIT run finished.
    Used by: main.
    Input: .abo path; returns: bool.
    """
    return "Calculation completed" in Path(abo).read_text(
        encoding="utf-8", errors="replace")


def epsilon_10(e0, ep1, corr_p1):
    """Transition level eps(+1/0).
    Used by: main.
    Inputs: E(0), E(+1) in Ha and the +1 correction in eV; returns: eps (eV
    above the VBM).
    """
    return (e0 - ep1) * HA_EV - corr_p1 - E_VBM


def main():
    """Compute eps(+1/0) and the moment at each U.
    Used by: command line.
    Writes results/transition_levels/<config>_u_scan.json.
    """
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default="er_ko")
    ap.add_argument("--prod-dir", type=Path, default=Path("abinit/production"))
    ap.add_argument("--output", type=Path, default=None,
                    help="default: results/transition_levels/<config>_u_scan.json")
    args = ap.parse_args()
    c = args.config
    output = args.output or Path(f"results/transition_levels/{c}_u_scan.json")
    corr_json = Path(CORR_JSON.format(c=c))

    if not corr_json.is_file():
        print(f"missing {corr_json}; run kumagai_correction.py first",
              file=sys.stderr)
        return 1
    corr = {int(k): v for k, v in
            json.loads(corr_json.read_text())["corrections_eV"].items()}
    corr_p1 = corr[1]

    rows = []
    for u_ev in [PRODUCTION_U] + SCAN_U:
        e, mom, missing = {}, None, []
        for q, tag in TAGS.items():
            if u_ev == PRODUCTION_U:
                base = PRODUCTION_RUNS[q].format(c=c)
            else:
                base = f"{c}_{u_tag(u_ev)}_{tag}_spin"
            abo = args.prod_dir / f"{base}.abo"
            if not abo.is_file() or not completed(abo):
                missing.append(base)
                continue
            e[q] = fe.extract_total_energy(abo)
            if q == 0:
                mom = moment_of(abo)
        if missing:
            rows.append({"U_eV": u_ev, "missing": missing})
            continue
        rows.append({
            "U_eV": u_ev,
            "E_q0_Ha": e[0], "E_qp1_Ha": e[1], "E_qm1_Ha": e[-1],
            "moment_muB": mom,
            "epsilon_p1_0_eV": epsilon_10(e[0], e[1], corr_p1),
            "production": u_ev == PRODUCTION_U,
        })

    print(f"--- {c}: Hubbard-U sensitivity of the (+1/0) transition level ---")
    print(f"    corrections: Kumagai-Oba, E_corr(+1) = {corr_p1:+.4f} eV; "
          f"E_VBM = {E_VBM} eV\n")
    print(f"    {'U (eV)':>8}  {'moment':>8}  {'eps(+1/0)':>10}   note")
    done = [r for r in rows if "missing" not in r]
    for r in rows:
        if "missing" in r:
            print(f"    {r['U_eV']:>8.2f}  {'—':>8}  {'—':>10}   "
                  f"NOT RUN: {', '.join(r['missing'])}")
            continue
        flag = "production U" if r["production"] else ""
        m = r["moment_muB"]
        if m is not None and not (2.5 <= m <= 3.6):
            flag = (flag + "  moment out of range: different 4f solution, "
                            "energy not comparable").strip()
        mtxt = f"{m:.3f}" if m is not None else "n/a"
        print(f"    {r['U_eV']:>8.2f}  {mtxt:>8}  "
              f"{r['epsilon_p1_0_eV']:>10.3f}   {flag}")

    if len(done) >= 2:
        eps = [r["epsilon_p1_0_eV"] for r in done]
        spread = max(eps) - min(eps)
        print(f"\n    spread across the sampled U range: {spread:.3f} eV")

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps({
        "config": c,
        "E_VBM_eV": E_VBM,
        "correction_eV": corr,
        "note": "statics at the U=7.21 relaxed geometry of each charge state; "
                "geometry fixed, so this isolates the electronic response to U",
        "points": rows,
    }, indent=2), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
